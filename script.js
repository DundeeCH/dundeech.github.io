let currentLang = 'en';

document.addEventListener('DOMContentLoaded', () => {
    
    // --- Language Switcher Logic ---
    const btnEn = document.getElementById('btn-en');
    const btnUk = document.getElementById('btn-uk');

    function setLanguage(lang) {
        currentLang = lang;
        
        // Update active class
        btnEn.classList.toggle('active', lang === 'en');
        btnUk.classList.toggle('active', lang === 'uk');
        
        // Update document title and lang attribute
        document.title = lang === 'en' ? "Danylo Vahanov | Resume" : "Данило Ваганов | Резюме";
        document.documentElement.lang = lang;

        // Replace all texts using data-i18n attributes
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                el.innerHTML = translations[lang][key];
            }
        });

        // Re-inject dynamic current year after footer translation updates innerHTML
        const yearSpan = document.getElementById('year');
        if(yearSpan) {
            yearSpan.textContent = new Date().getFullYear();
        }
    }

    if(btnEn && btnUk) {
        btnEn.addEventListener('click', () => setLanguage('en'));
        btnUk.addEventListener('click', () => setLanguage('uk'));
    }

    // Set initial dynamic year
    const yearSpan = document.getElementById('year');
    if(yearSpan) yearSpan.textContent = new Date().getFullYear();

    // --- Interactive skill tag highlighting ---
    const tags = document.querySelectorAll('.skill-tag');
    tags.forEach(tag => {
        tag.addEventListener('click', () => {
            tag.classList.toggle('highlight-skill');
        });
    });

    // --- Smooth sequential fade-in animation ---
    const sections = document.querySelectorAll('section');
    sections.forEach((section, index) => {
        section.style.opacity = '1';
        section.style.transform = 'translateY(0)';
        section.style.transition = `all 0.6s ease ${index * 0.12}s`;
    });

    // --- Accordion expand/collapse logic ---
    const accordionToggle = document.getElementById('accordionToggle');
    const accordionSection = document.getElementById('additional');

    if (accordionToggle && accordionSection) {
        accordionToggle.addEventListener('click', () => {
            accordionSection.classList.toggle('active');
        });
    }

    // --- Email Copy to Clipboard Logic ---
    const copyEmailBtn = document.getElementById('copyEmailBtn');
    const emailTooltip = document.getElementById('emailTooltip');

    if (copyEmailBtn && emailTooltip) {
        copyEmailBtn.addEventListener('click', () => {
            const emailAddress = copyEmailBtn.getAttribute('data-email');
            
            navigator.clipboard.writeText(emailAddress).then(() => {
                // Use translated string for "Copied!"
                emailTooltip.textContent = translations[currentLang].tooltipCopied;
                
                setTimeout(() => {
                    // Revert back to translated string for "Click to copy"
                    emailTooltip.textContent = translations[currentLang].tooltipCopy;
                }, 1500);
            }).catch(err => {
                console.error('Could not copy text: ', err);
            });
        });
    }
});